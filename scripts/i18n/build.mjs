// Build the runtime dictionaries (assets/i18n/<code>.js) from the translation memory.
// Usage: node scripts/i18n/build.mjs
// Only translations whose English source still matches the current site are shipped;
// anything stale or missing falls back to English on the page.
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { config, catalog, locale, targets, items, inScope, validate, rel, writeJSON, words } from './lib.mjs';

const cfg = config(), cat = catalog(), all = items(cat);
const waves = Object.keys(cfg.waves);
const coverage = {}, langs = [{ code: cfg.source.code, lang: cfg.source.lang, name: cfg.source.name, dir: cfg.source.dir, status: 'source' }];

for (const l of targets(cfg)) {
  const file = rel('assets/i18n', l.code + '.js');
  if (!l.enabled) { if (fs.existsSync(file)) fs.rmSync(file); continue; }
  const loc = locale(l.code), dict = { lang: l.code, u: {}, p: {} };
  const cov = Object.fromEntries(waves.map(w => [w, { items: 0, done: 0, words: 0, wordsDone: 0 }]));
  let stale = 0, invalid = 0;
  for (const it of all) {
    const e = loc.entries[it.id];
    let ok = false;
    if (e) {
      if (e.s !== it.en) stale++;
      else if (validate(it.en, e.t, it.kind === 'p').length) invalid++;
      else {
        ok = true;
        if (it.kind === 'p') dict.p[it.id.slice(2)] = e.t; else dict.u[it.id] = e.t;
      }
    }
    for (const w of waves) if (inScope(it.routes, cfg.waves[w])) {
      const c = cov[w], n = words(it.en);
      c.items++; c.words += n; if (ok) { c.done++; c.wordsDone += n; }
    }
  }
  const body = '/* Generated by scripts/i18n/build.mjs from i18n/locales/' + l.code + '.json. Do not edit. */\n' +
    'window.SIDUS_I18N_DICT=' + JSON.stringify(dict) + ';\n';
  fs.writeFileSync(file, body);
  const v = createHash('sha256').update(body).digest('hex').slice(0, 10);
  langs.push({ code: l.code, lang: l.lang, name: l.name, dir: l.dir, status: l.status, v });
  coverage[l.code] = { ...cov, stale, invalid };
}

// Tell the runtime which languages exist and which dictionary version to fetch.
const rt = rel('assets/i18n/i18n.js');
const src = fs.readFileSync(rt, 'utf8');
const next = src.replace(/\/\*LANGS\*\/[\s\S]*?\/\*END LANGS\*\//, '/*LANGS*/' + JSON.stringify(langs) + '/*END LANGS*/');
if (next !== src) fs.writeFileSync(rt, next);

writeJSON('i18n/coverage.json', { built: new Date().toISOString(), sourceCommit: cat.commit, languages: coverage });
const pct = (a, b) => (b ? Math.round((1000 * a) / b) / 10 : 100) + '%';
console.log('language  ' + waves.map(w => w.padEnd(22)).join('') + 'stale invalid');
for (const [code, c] of Object.entries(coverage)) {
  console.log(code.padEnd(10) + waves.map(w => `${pct(c[w].wordsDone, c[w].words)} (${c[w].done}/${c[w].items})`.padEnd(22)).join('') + String(c.stale).padEnd(6) + c.invalid);
}
